# CRITICAL's fonts, anti-aliased bitmaps for app/fonts.c (each glyph cropped to its ink):
#   font_lbl, font_hdr  Barlow Condensed SemiBold (the panels' engraved labels, headers)
#   font_dat, font_val  B612 Mono Bold (values: the cockpit font Airbus had made for legibility)
# Both SIL Open Font License 1.1 (assets/fonts/OFL-*.txt).   tools/mkfont.py OUT.c
import sys
from PIL import Image, ImageDraw, ImageFont
BAR = 'assets/fonts/BarlowCondensed-SemiBold.woff'
B612 = 'assets/fonts/B612Mono-Bold.woff'
CHARS = [chr(c) for c in range(32, 96)] + ['°', 'Δ', '±', '→', '·', '▲', '▼', 'µ']
SIZES = [('font_lbl', BAR, 14, 4), ('font_hdr', BAR, 18, 4), ('font_dat', B612, 12, 4), ('font_val', B612, 20, 4)]
NARROW = '.:,'                                     # (mono: these take half a cell, so 100.0 and 14:32 read as numbers)

def build(path, px, bpp):
    f = ImageFont.truetype(path, px)
    asc, desc = f.getmetrics()
    glyphs, bits = [], bytearray()
    for ch in CHARS:
        try: adv = round(f.getlength(ch))
        except Exception: adv = 0
        im = Image.new('L', (px * 3, px * 3), 0)
        ImageDraw.Draw(im).text((px, px), ch, font=f, fill=255)
        bb = im.getbbox()
        if ch in '▲▼':                                  # (not in the fonts: drawn here)
            s = max(5, px * 5 // 11); im = Image.new('L', (px * 3, px * 3), 0); d = ImageDraw.Draw(im)
            top = px + asc - round(px * 0.72); x = px
            d.polygon([(x, top + s), (x + s, top + s), (x + s / 2, top)] if ch == '▲' else [(x, top), (x + s, top), (x + s / 2, top + s)], fill=255)
            bb = im.getbbox(); adv = s + 2
        if not bb:
            glyphs.append((0, 0, 0, 0, adv, len(bits))); continue
        x0, y0, x1, y1 = bb
        w, h = x1 - x0, y1 - y0
        off = len(bits); nib = []
        for y in range(y0, y1):
            for x in range(x0, x1): nib.append((im.getpixel((x, y)) * ((1 << bpp) - 1) + 127) // 255)
        per = 8 // bpp
        while len(nib) % per: nib.append(0)
        for i in range(0, len(nib), per):
            b = 0
            for k in range(per): b = b << bpp | nib[i + k]
            bits.append(b)
        if path == B612 and ch in NARROW:                # the narrow ones: centred in half a cell
            half = (adv + 1) // 2; sh = (adv - half) // 2; x0 -= sh; adv = half
        glyphs.append((w, h, x0 - px, y0 - px, adv, off))
    return asc, desc, glyphs, bits

out = ['/* SPDX-License-Identifier: GPL-3.0-only', ' * Generated by tools/mkfont.py: do not edit.',
       ' * Glyphs rendered from Barlow Condensed SemiBold and B612 Mono Bold, SIL Open Font License 1.1. */', '#include "gfx.h"', '']
for name, path, px, bpp in SIZES:
    asc, desc, glyphs, bits = build(path, px, bpp)
    out.append(f'static const uint8_t {name}_bits[{len(bits)}] = {{')
    for i in range(0, len(bits), 24): out.append('    ' + ','.join(str(b) for b in bits[i:i + 24]) + ',')
    out.append('};')
    out.append(f'static const gfx_glyph {name}_g[{len(glyphs)}] = {{')
    for g in glyphs: out.append('    {%d,%d,%d,%d,%d,%d},' % g)
    out.append('};')
    H = glyphs[ord('H') - 32]
    out.append(f'const gfx_font {name} = {{ {name}_g, {name}_bits, {len(glyphs)}, {asc}, {asc + desc}, {H[1]}, {H[3]}, {bpp} }};')
    out.append('')
    print(f'{name}: {px} px, cap {H[1]}, {len(bits)} bytes, M={glyphs[ord("M")-32][4]} 0={glyphs[16][4]}', file=sys.stderr)
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
